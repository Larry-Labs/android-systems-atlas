"""Run existing UI regression checks, then verify the glossary feature."""
import json
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
suite = runpy.run_path(str(ROOT / 'tests/browser-smoke.py'))
browser, evaluate, check, navigate, checks = [suite[k] for k in ['browser','evaluate','check','navigate','checks']]
base_count = len(checks)
navigate('glossary')
check('Glossary contains 34 entries', 'document.querySelectorAll(".glossary-card").length === 34')
browser('fill', '#glossary-filter', '原生接口')
check('Chinese term name search finds JNI', 'document.querySelectorAll(".glossary-card").length === 1 && document.querySelector(".glossary-card").dataset.term === "jni"')
browser('click', '.glossary-card')
check('Term modal displays official source', 'document.querySelector("#term-dialog").open && document.querySelector("#term-title").textContent.trim() === "JNI" && document.querySelector(".term-dialog-links a").href.startsWith("https://developer.android.com/")')
browser('click', '[data-term-language]')
check('Modal language switch updates definition', 'document.documentElement.lang === "en" && document.querySelector(".term-dialog-definition").textContent.includes("managed code")')
browser('press', 'Escape')
check('Modal closes and glossary query survives language switch', '!document.querySelector("#term-dialog").open && document.querySelector("#glossary-filter").value === "原生接口" && document.querySelectorAll(".glossary-card").length === 1')
browser('fill', '#glossary-filter', 'pulse-code')
check('Full English name search finds PCM', 'document.querySelectorAll(".glossary-card").length === 1 && document.querySelector(".glossary-card").dataset.term === "pcm"')
browser('fill', '#glossary-filter', '<img src=x onerror=alert(1)>')
check('Special input produces safe empty state', '!!document.querySelector("#glossary-list .empty-state") && !document.querySelector("#glossary-list img")')
browser('click', '[data-lang="zh"]')
check('Special query survives rendering as text', 'document.querySelector("#glossary-filter").value === "<img src=x onerror=alert(1)>" && !document.querySelector("#main img")')
browser('fill', '#glossary-filter', 'HIDL')
browser('click', '.glossary-card')
check('HIDL shows deprecation and version context', '!!document.querySelector("#term-title .deprecated-label") && document.querySelector(".term-boundary").textContent.includes("Android 10")')
browser('click', '[data-close="term-dialog"]')
browser('press', '/')
browser('fill', '#search-input', 'Java Native Interface')
check('Global search includes full-name term results', 'document.querySelectorAll(".term-search-result").length === 1 && document.querySelector(".term-search-result").dataset.term === "jni"')
browser('click', '.term-search-result')
check('Search opens definition without stacked modals', 'document.querySelector("#term-dialog").open && !document.querySelector("#search-dialog").open && document.querySelectorAll("dialog[open]").length === 1')
browser('click', '.term-dialog-links a.text-link')
check('Related domain link navigates and dismisses modal', 'location.hash === "#/domain/runtime" && !document.querySelector("#term-dialog").open')
navigate('domain/audio')
check('Article exposes inline term definitions', 'document.querySelectorAll(".inline-term").length > 0 && !document.querySelector("a .inline-term,button .inline-term")')
browser('click', '.inline-term')
check('Inline term opens nonmodal popover', '!document.querySelector("#term-popover").hidden && !document.querySelector("#term-dialog").open && location.hash === "#/domain/audio"')
scroll = evaluate('window.scrollY')
browser('press', 'Escape')
check('Closing definition returns to article', 'document.querySelector("#term-popover").hidden && !document.querySelector("#term-dialog").open && location.hash === "#/domain/audio"')
assert abs(evaluate('window.scrollY') - scroll) < 2
checks.append('Inline definition preserves reading scroll')
for language in ['zh','en']:
    browser('click', f'[data-lang="{language}"]')
    navigate('glossary')
    browser('fill', '#glossary-filter', '')
    browser('set', 'viewport', '390', '844')
    check(f'{language} glossary has no mobile overflow', 'document.documentElement.scrollWidth <= innerWidth')
    browser('click', '.glossary-card')
    check(f'{language} term dialog fits mobile viewport', 'document.querySelector("#term-dialog").getBoundingClientRect().right <= innerWidth && document.querySelector("#term-dialog").scrollWidth <= document.querySelector("#term-dialog").clientWidth')
    browser('screenshot', str(ROOT / f'artifacts/term-mobile-{language}.png'))
    browser('press', 'Escape')
    browser('set', 'viewport', '1440', '1080')
    check(f'{language} glossary has no desktop overflow', 'document.documentElement.scrollWidth <= innerWidth')
    if language == 'en':
        check('English glossary has no untranslated Chinese', '!/[\u4e00-\u9fff]/.test(document.querySelector("#main").innerText)')
browser('click','[data-lang="zh"]')
evaluate('window.scrollTo(0,0); document.activeElement.blur()')
browser('screenshot', str(ROOT/'artifacts/glossary-desktop.png'), '--full')
errors=browser('errors').get('errors',[])
assert not errors, errors
checks.append('No browser runtime errors')
(ROOT/'artifacts/glossary-smoke.json').write_text(json.dumps({'regression_passed':base_count,'glossary_passed':len(checks)-base_count,'checks':checks[base_count:]},ensure_ascii=False,indent=2)+'\n')
print(f'PASS: {base_count} existing checks + {len(checks)-base_count} glossary checks')
